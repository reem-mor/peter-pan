"""Build, push ECR image, and roll EC2 containers via SSM — values never printed.

Usage (from repo root, with AWS creds + Docker):
    python scripts/deploy_ec2_rolling.py
"""

from __future__ import annotations

import json
import secrets
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REGION = "us-east-1"
REPO = "peter-pan"
INSTANCE_ID = "i-072591e3ce8b322f3"
SECRET_ID = "peter-pan/deploy"
ACCOUNT = "329597159579"
ECR = f"{ACCOUNT}.dkr.ecr.{REGION}.amazonaws.com"


def _run(cmd: list[str], *, check: bool = True) -> subprocess.CompletedProcess[str]:
    return subprocess.run(cmd, check=check, capture_output=True, text=True)


def _git_sha() -> str:
    return _run(["git", "-C", str(ROOT), "rev-parse", "--short", "HEAD"]).stdout.strip()


def _load_env_keys() -> dict[str, str]:
    wanted = {"ANTHROPIC_API_KEY", "PINECONE_API_KEY", "VOYAGE_API_KEY", "PP_API_TOKEN"}
    values: dict[str, str] = {}
    for env_path in (ROOT / ".env", Path(r"C:\dev\peter-pan\.env")):
        if not env_path.exists():
            continue
        for line in env_path.read_text(encoding="utf-8").splitlines():
            line = line.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            name, value = line.split("=", 1)
            name, value = name.strip(), value.strip().strip('"').strip("'")
            if name in wanted and value:
                values[name] = value
    if "PP_API_TOKEN" not in values:
        values["PP_API_TOKEN"] = secrets.token_urlsafe(32)
        wt_env = ROOT / ".env"
        existing = wt_env.read_text(encoding="utf-8") if wt_env.exists() else ""
        if "PP_API_TOKEN=" not in existing:
            with wt_env.open("a", encoding="utf-8") as fh:
                fh.write("\n# generated by deploy_ec2_rolling.py — never commit\n")
                fh.write(f"PP_API_TOKEN={values['PP_API_TOKEN']}\n")
    return values


def _put_secret(values: dict[str, str]) -> None:
    payload_path = ROOT / ".deploy-secret.tmp.json"
    payload_path.write_text(json.dumps(values), encoding="utf-8")
    try:
        upd = _run(
            [
                "aws",
                "secretsmanager",
                "put-secret-value",
                "--region",
                REGION,
                "--secret-id",
                SECRET_ID,
                "--secret-string",
                f"file://{payload_path.as_posix()}",
            ],
            check=False,
        )
        if upd.returncode != 0:
            print(f"secret update failed: {upd.stderr.strip()[:200]}")
            sys.exit(1)
        print(f"secret updated: {SECRET_ID} (keys={sorted(values)})")
    finally:
        payload_path.unlink(missing_ok=True)


def _docker_push(tag: str) -> str:
    image = f"{ECR}/{REPO}:{tag}"
    login = _run(["aws", "ecr", "get-login-password", "--region", REGION])
    auth = subprocess.run(
        ["docker", "login", "--username", "AWS", "--password-stdin", ECR],
        input=login.stdout,
        capture_output=True,
        text=True,
        check=False,
    )
    if auth.returncode != 0:
        print(f"docker login failed: {auth.stderr.strip()[:200]}")
        sys.exit(1)
    build = _run(["docker", "build", "-t", image, str(ROOT)], check=False)
    if build.returncode != 0:
        print(f"docker build failed:\n{build.stderr[-800:]}")
        sys.exit(1)
    push = _run(["docker", "push", image], check=False)
    if push.returncode != 0:
        print(f"docker push failed:\n{push.stderr[-800:]}")
        sys.exit(1)
    print(f"pushed: {image}")
    return image


def _ssm_roll(image: str) -> None:
    # Keep host-port mapping identical to infra/aws/stack.yaml UserData.
    commands = [
        "set -euo pipefail",
        f"REGION={REGION}",
        f"IMAGE={image}",
        f"SECRET_ID={SECRET_ID}",
        f"aws ecr get-login-password --region {REGION} "
        f"| docker login --username AWS --password-stdin {ECR}",
        "SECRET_JSON=$(aws secretsmanager get-secret-value "
        f"--region {REGION} --secret-id {SECRET_ID} "
        "--query SecretString --output text)",
        "ANTHROPIC_API_KEY=$(echo \"$SECRET_JSON\" | jq -r '.ANTHROPIC_API_KEY // empty')",
        "PINECONE_API_KEY=$(echo \"$SECRET_JSON\" | jq -r '.PINECONE_API_KEY // empty')",
        "VOYAGE_API_KEY=$(echo \"$SECRET_JSON\" | jq -r '.VOYAGE_API_KEY // empty')",
        "PP_API_TOKEN=$(echo \"$SECRET_JSON\" | jq -r '.PP_API_TOKEN // empty')",
        "unset SECRET_JSON",
        "install -d -m 770 -o 1000 -g 1000 "
        "/opt/peterpan/usage /opt/peterpan/agent-data "
        "/opt/peterpan/ppos-data /opt/peterpan/knowledge",
        'docker pull "$IMAGE"',
        "docker rm -f predictor rag guardrails agent ppos >/dev/null 2>&1 || true",
        # Seed baked corpus into the host knowledge mount BEFORE rag starts
        # (empty mount would hide /app/knowledge → corpus_size=0).
        'docker run --rm -v /opt/peterpan/knowledge:/out "$IMAGE" '
        "sh -c 'cp -a /app/knowledge/. /out/ && chown -R 1000:1000 /out'",
        # predictor
        "docker run -d --restart unless-stopped --name predictor "
        "-e SERVICE=predictor -e PP_ENV=mirage "
        "-e PP_USAGE_LOG_PATH=/app/usage-shared/usage.jsonl "
        '-e "PP_API_TOKEN=$PP_API_TOKEN" '
        '-v /opt/peterpan/usage:/app/usage-shared -p 8001:8000 "$IMAGE"',
        # rag
        "docker run -d --restart unless-stopped --name rag "
        "-e SERVICE=rag -e PP_ENV=mirage "
        "-e PP_USAGE_LOG_PATH=/app/usage-shared/usage.jsonl "
        "-e PP_RAG_BACKEND=pinecone "
        '-e "PP_API_TOKEN=$PP_API_TOKEN" '
        '-e "PINECONE_API_KEY=$PINECONE_API_KEY" '
        '-e "VOYAGE_API_KEY=$VOYAGE_API_KEY" '
        "-v /opt/peterpan/usage:/app/usage-shared "
        '-v /opt/peterpan/knowledge:/app/knowledge -p 8002:8000 "$IMAGE"',
        # guardrails
        "docker run -d --restart unless-stopped --name guardrails "
        "-e SERVICE=guardrails -e PP_ENV=mirage "
        "-e PP_USAGE_LOG_PATH=/app/usage-shared/usage.jsonl "
        '-e "PP_API_TOKEN=$PP_API_TOKEN" '
        '-v /opt/peterpan/usage:/app/usage-shared -p 8003:8000 "$IMAGE"',
        # agent — in-process search() needs PP_RAG_BACKEND + keys too;
        # Bedrock via instance profile; AgentCore ARN unset => local
        "docker run -d --restart unless-stopped --name agent "
        "-e SERVICE=agent -e PP_ENV=mirage "
        "-e PP_USAGE_LOG_PATH=/app/usage-shared/usage.jsonl "
        "-e PP_LLM=bedrock "
        f"-e PP_BEDROCK_MODEL_ID=us.anthropic.claude-sonnet-4-5-20250929-v1:0 "
        f"-e AWS_REGION={REGION} "
        "-e PP_AGENT_PROVIDER=local "
        "-e PP_RAG_BACKEND=pinecone "
        '-e "PP_API_TOKEN=$PP_API_TOKEN" '
        '-e "ANTHROPIC_API_KEY=$ANTHROPIC_API_KEY" '
        '-e "PINECONE_API_KEY=$PINECONE_API_KEY" '
        '-e "VOYAGE_API_KEY=$VOYAGE_API_KEY" '
        "-v /opt/peterpan/usage:/app/usage-shared "
        '-v /opt/peterpan/agent-data:/app/data -p 8004:8000 "$IMAGE"',
        # ppos
        "docker run -d --restart unless-stopped --name ppos "
        "-e SERVICE=ppos -e PP_ENV=mirage "
        "-e PP_USAGE_LOG_PATH=/app/usage-shared/usage.jsonl "
        '-e "PP_API_TOKEN=$PP_API_TOKEN" '
        "-v /opt/peterpan/usage:/app/usage-shared "
        '-v /opt/peterpan/ppos-data:/app/data -p 8005:8000 "$IMAGE"',
        # Idempotent Pinecone upsert of the baked corpus (empty index →
        # pinecone backend with 0 matches and thin stories).
        "docker run --rm -e PP_RAG_BACKEND=pinecone "
        '-e "PINECONE_API_KEY=$PINECONE_API_KEY" '
        '-e "VOYAGE_API_KEY=$VOYAGE_API_KEY" '
        '"$IMAGE" python scripts/ingest_kb.py',
        "unset ANTHROPIC_API_KEY PINECONE_API_KEY VOYAGE_API_KEY PP_API_TOKEN",
        "sleep 5",
        "for p in 8001 8002 8003 8004 8005; do "
        'echo -n "$p "; curl -sS -m 3 "http://127.0.0.1:$p/healthz" || echo FAIL; echo; done',
    ]
    params_path = ROOT / ".ssm-roll.tmp.json"
    params_path.write_text(json.dumps({"commands": commands}), encoding="utf-8")
    try:
        cid = _run(
            [
                "aws",
                "ssm",
                "send-command",
                "--instance-ids",
                INSTANCE_ID,
                "--document-name",
                "AWS-RunShellScript",
                "--comment",
                f"peter-pan roll {image.split(':')[-1]}",
                "--parameters",
                f"file://{params_path.as_posix()}",
                "--query",
                "Command.CommandId",
                "--output",
                "text",
            ]
        ).stdout.strip()
        print(f"ssm command: {cid}")
        for _ in range(60):
            time.sleep(5)
            inv = _run(
                [
                    "aws",
                    "ssm",
                    "get-command-invocation",
                    "--command-id",
                    cid,
                    "--instance-id",
                    INSTANCE_ID,
                    "--output",
                    "json",
                ]
            )
            data = json.loads(inv.stdout)
            status = data.get("Status")
            if status in {"Success", "Failed", "Cancelled", "TimedOut"}:
                print(f"ssm status: {status}")
                print(data.get("StandardOutputContent", "")[-2500:])
                err = (data.get("StandardErrorContent") or "")[-800:]
                if err:
                    print("ssm stderr (tail):", err)
                if status != "Success":
                    sys.exit(1)
                return
        print("ssm timed out waiting for completion")
        sys.exit(1)
    finally:
        params_path.unlink(missing_ok=True)


def main() -> int:
    tag = _git_sha()
    print(f"deploy tag: {tag}")
    values = _load_env_keys()
    missing = [k for k in ("PINECONE_API_KEY", "VOYAGE_API_KEY") if k not in values]
    if missing:
        print(f"missing required keys in .env: {missing}")
        sys.exit(2)
    _put_secret(values)
    image = _docker_push(tag)
    _ssm_roll(image)
    print("rolling deploy complete")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
